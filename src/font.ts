export function drawPixelText(text: string, x: number, y: number, color: RGB) {
  ctx.fillStyle = rgbStr(color);
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = FONT4X5[ch] ?? FONT4X5[' '];
    for (let row = 0; row < 5; row++) {
      for (let col = 0; col < 4; col++) {
        if (glyph[row][col] === '#') ctx.fillRect(cx + col, y + row, 1, 1);
      }
    }
    cx += 5;
  }
}
export function textWidth(text: string): number {
  return text.length * 5 - 1;
}
export function drawPixelTextCentered(text: string, cx: number, y: number, color: RGB) {
  drawPixelText(text, Math.round(cx - textWidth(text) / 2), y, color);
}
